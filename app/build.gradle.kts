import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
}

// Release signing: set these env vars (CI reads them from repo secrets).
// Without them, release builds fall back to the debug key so CI always produces an APK.
val keystorePath: String? = System.getenv("BITKEYS_KEYSTORE")

android {
    namespace = "com.bitdroid.keys"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.bitdroid.keys"
        minSdk = 31
        targetSdk = 35
        versionCode = 1
        versionName = "0.1.0"
    }

    signingConfigs {
        create("release") {
            if (keystorePath != null) {
                storeFile = file(keystorePath)
                storePassword = System.getenv("BITKEYS_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("BITKEYS_KEY_ALIAS")
                keyPassword = System.getenv("BITKEYS_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"))
            signingConfig = if (keystorePath != null) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug")
            }
        }
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        buildConfig = false
    }
}

kotlin {
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_17)
    }
}

base {
    archivesName.set("bitKeys-${android.defaultConfig.versionName}")
}
